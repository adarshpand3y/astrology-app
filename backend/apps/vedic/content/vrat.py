KEYS = ("ekadashi_shukla", "ekadashi_krishna", *_FESTIVALS)


def _ekadashi(key: str, lang: str, month: str | None, is_adhika: bool) -> dict:
    hi = lang == "hi"
    paksha = "shukla" if key == "ekadashi_shukla" else "krishna"
    names = ADHIKA_EKADASHI[paksha] if is_adhika else EKADASHI_NAMES.get((month, paksha))
    name = names[1 if hi else 0] if names else ""
    steps = list(_EKADASHI_STEPS[1 if hi else 0])
    note = EKADASHI_NOTE.get(names[0]) if names else None
    if note:
        steps.insert(1, note[1 if hi else 0])
    return {
        "key": key, "glyph": "◑" if paksha == "shukla" else "◐", "fast": True,
        "name": (f"{name} एकादशी" if hi else f"{name} Ekadashi") if name else ("एकादशी" if hi else "Ekadashi"),
        "how": ("विष्णु के लिए व्रत; अन्न का त्याग, द्वादशी को पारण।" if hi
                else "A fast for Vishnu: no grains, broken on Dwadashi morning."),
        "steps": steps,
    }


def observance(key: str, lang: str, month: str | None = None, is_adhika: bool = False) -> dict:
    """Display data for one observance: name, glyph, whether it's a fast, a one-line summary and the
    steps of what to do. `month` / `is_adhika` (amanta) name an Ekadashi."""
    if key.startswith("ekadashi"):
        return _ekadashi(key, lang, month, is_adhika)
    glyph, fast, names, how, steps = _FESTIVALS[key]
    i = 1 if lang == "hi" else 0
    return {"key": key, "glyph": glyph, "fast": fast, "name": names[i], "how": how[i], "steps": list(steps[i])}
